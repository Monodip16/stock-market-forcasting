"""
Visualization and Metric Reporting Module.

This module provides:
1. Publication-quality Matplotlib visualization comparing Actual prices against
   ARIMA and LSTM forecasts on the exact same hold-out test dates.
2. Saving and terminal rendering of the comparative performance metrics table (MAE, RMSE).
"""

import os
import matplotlib
# Default to non-interactive Agg backend to support headless server/terminal execution
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd


def plot_model_comparison(
    actual_series: pd.Series,
    arima_forecast: pd.Series | None = None,
    lstm_forecast: pd.Series | None = None,
    ticker: str = "AAPL",
    save_path: str = "outputs/arima_vs_lstm.png",
    display: bool = False,
) -> None:
    """
    Generate ONE clean Matplotlib figure comparing actual stock closing prices
    against ARIMA forecast and LSTM forecast on the exact same test dates.

    Parameters:
    -----------
    actual_series : pd.Series
        Ground-truth actual test closing prices with DatetimeIndex.
    arima_forecast : pd.Series or None
        Forecast generated by ARIMA model on test dates.
    lstm_forecast : pd.Series or None
        Forecast generated by LSTM model on test dates.
    ticker : str
        Stock ticker symbol.
    save_path : str
        Destination path for saving the PNG plot.
    display : bool
        Whether to attempt calling plt.show() (safe fallback if headless).
    """
    os.makedirs(os.path.dirname(os.path.abspath(save_path)), exist_ok=True)

    plt.figure(figsize=(14, 7), dpi=300)

    # 1. Actual closing price line
    plt.plot(
        actual_series.index,
        actual_series.values,
        label="Actual",
        color="#1f77b4",
        linewidth=2.2,
        alpha=0.9,
    )

    # 2. ARIMA forecast line
    if arima_forecast is not None:
        plt.plot(
            arima_forecast.index,
            arima_forecast.values,
            label="ARIMA Forecast",
            color="#ff7f0e",
            linestyle="--",
            linewidth=2.0,
            alpha=0.9,
        )

    # 3. LSTM forecast line
    if lstm_forecast is not None:
        plt.plot(
            lstm_forecast.index,
            lstm_forecast.values,
            label="LSTM Forecast",
            color="#2ca02c",
            linestyle="-.",
            linewidth=2.0,
            alpha=0.9,
        )

    plt.title(
        f"Stock Market Forecasting: Actual vs. ARIMA vs. LSTM ({ticker})",
        fontsize=15,
        fontweight="bold",
        pad=15,
    )
    plt.xlabel("Date", fontsize=12, labelpad=8)
    plt.ylabel("Closing Price (USD)", fontsize=12, labelpad=8)
    plt.grid(True, linestyle="--", alpha=0.5)
    plt.legend(
        loc="upper left",
        fontsize=11,
        frameon=True,
        facecolor="white",
        edgecolor="#cccccc",
        shadow=True,
    )
    plt.tight_layout()

    # Save high-resolution figure
    plt.savefig(save_path, dpi=300)
    print(f"[INFO] Final comparison plot saved to: {save_path}")

    # Optional display
    if display:
        try:
            plt.show()
        except Exception:
            pass

    plt.close()


def save_and_display_metrics(
    metrics_records: list[dict],
    save_path: str = "outputs/metrics.csv",
) -> pd.DataFrame:
    """
    Save comparative metrics table to CSV and print a clean formatted summary in the terminal.

    Parameters:
    -----------
    metrics_records : list of dict
        List of dictionaries with keys: 'Model', 'MAE', 'RMSE' (and optionally 'MAPE (%)').
    save_path : str
        File destination path for saving metrics CSV.

    Returns:
    --------
    pd.DataFrame:
        Formatted metrics dataframe.
    """
    os.makedirs(os.path.dirname(os.path.abspath(save_path)), exist_ok=True)

    df_metrics = pd.DataFrame(metrics_records)
    # Ensure exact column order required
    required_cols = ["Model", "MAE", "RMSE"]
    extra_cols = [c for c in df_metrics.columns if c not in required_cols]
    final_cols = required_cols + extra_cols
    df_metrics = df_metrics[final_cols]

    # Save CSV
    df_metrics.to_csv(save_path, index=False)
    print(f"[INFO] Metrics table saved to: {save_path}\n")

    # Clean terminal table
    print("=" * 55)
    print("           MODEL PERFORMANCE SUMMARY (TEST SET)          ")
    print("=" * 55)
    header = f"{'Model':<15} | {'MAE (USD)':<12} | {'RMSE (USD)':<12}"
    if "MAPE" in df_metrics.columns:
        header += f" | {'MAPE (%)':<10}"
    print(header)
    print("-" * 55)

    for _, row in df_metrics.iterrows():
        line = f"{row['Model']:<15} | {row['MAE']:<12.4f} | {row['RMSE']:<12.4f}"
        if "MAPE" in df_metrics.columns:
            line += f" | {row['MAPE']:<10.2f}"
        print(line)
    print("=" * 55)

    return df_metrics
